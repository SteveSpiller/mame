/*
    cocovga_charrom.h

    CoCoVGA character generator deltas over the MC6847 character ROMs.

    CoCoVGA regenerates the VDG character set inside its FPGA.  Almost
    every glyph it draws is the MC6847 or MC6847T1 character generator ROM
    image expanded into CoCoVGA's own 8x12 cell, and the device expands
    both ROM images it carries at run time, through the shared
    mc6847_charset helpers.  This header carries only what the FPGA
    generates itself and what therefore cannot be derived from those ROMs:

      * the lowercase bank, which the FPGA synthesises and no MC6847 part
        stores; and
      * the small set of glyphs whose FPGA rows deliberately differ from the
        ROM expansion.

    It is a set of CoCoVGA-specific generator deltas layered over the
    ROM-backed MC6847 bases, not a second copy of a character generator ROM:
    every glyph not named here comes from one of the two ROM images at run
    time, and the tables below are the differences the hardware introduces.

    Reproduced with authorization of rights holder Stephen Spiller and
    contributed under the BSD-3-Clause license of this file.  The FPGA
    sources are not publicly redistributed, so the exact revision the values
    came from is pinned here by hash:

        snapshot    62b780a9d8117c2c591e69191b7136bba02f053a
        file        CharRom.v
        sha256      60023fccf196f6a0d1c52f3cc1c402a24b5110ebf90e7e8c831d2c82a0f45226
        file        LowercaseCharRom.v
        sha256      3024dff09e5cff2f8a3de4d78d6af9c45b2ef48b57ea1e687375ce7f4bc2ddbd

    Public documentation of the same behaviour:

        http://cocovga.com/documentation/specifications/
        http://cocovga.com/documentation/software-mode-control/

    tests/emu/video/generate_cocovga_fixtures.py regenerates this file byte
    for byte from the pinned sources; --check verifies it in place.

    Derivation, which can be repeated from those sources alone:

      * decode every "N'hCC:" / "4'hRR: byteval = 8'hVV;" assignment in
        CharRom.v and LowercaseCharRom.v into
        rows[bank][character][row], where bank 1 is the MC6847T1 bank and
        bank 0 the standard MC6847 bank;
      * expand mc6847_charset.bin (CRC 3b22d071, SHA1 5e9d68e55e73cae3d28adaff34fe115e00029009,
        sha256 3ffb60b575a7edb088a7c64bb61ce4173febd6aaaedfa998c47d8b4945080e7d) into 8x12 glyph rows;
      * expand mc6847t1_charset_needredump.bin (CRC 42e62f8d, SHA1 1f09a076732a1e4b132cf298f0d1747df817e1c6,
        sha256 61498c6d2d252bd5a073ce62ecdc1ef1aa85936b2187d9d4d09e90a5c1fcd08e) into 8x12 glyph rows;
      * shift the T1 rows one row down and one pixel towards the left edge
        of the cell, as CoCoVGA does when it draws the T1 bank;
      * keep the lowercase bank as decoded, and list the text characters
        whose FPGA rows differ from the ROM-derived rows.
*/

